export function translateError(err: unknown, lang: Lang): string {
  const dict = TRANSLATIONS[lang].errors as Record<string, string>
  if (err && typeof err === 'object' && 'code' in err) {
    const code = String((err as { code: unknown }).code)
    const params = ((err as { params?: Record<string, unknown> }).params ?? {}) as Record<string, unknown>
    const base = dict[code]
    if (base) {
      const details: string[] = []
      if (params.product) details.push(String(params.product))
      if (params.username) details.push(String(params.username))
      if (params.code) details.push(`Code: ${params.code}`)
      if (params.sku) details.push(`SKU: ${params.sku}`)
      if (typeof params.available === 'number') {
        const avail = (params.available / 1000).toLocaleString('fr-MA', { maximumFractionDigits: 3 })
        details.push(lang === 'ar' ? `المتوفر: ${avail}` : `Disponible : ${avail}`)
      }
      if (typeof params.max === 'number') {
        details.push(`Max: ${params.max}%`)
      }
      if (typeof params.seconds === 'number') {
        details.push(lang === 'ar' ? `${params.seconds} ثانية` : `${params.seconds}s`)
      }
      if (typeof params.remaining === 'number' && params.remaining > 0 && params.remaining <= 2) {
        details.push(
          lang === 'ar'
            ? `المحاولات المتبقية: ${params.remaining}`
            : `Tentatives restantes : ${params.remaining}`
        )
      }
      if (typeof params.limit === 'number') {
        const lim = (params.limit / 100).toFixed(2)
        details.push(lang === 'ar' ? `السقف: ${lim} د.م.` : `Plafond : ${lim} DH`)
      }
      if (typeof params.balance === 'number') {
        const bal = (params.balance / 100).toFixed(2)
        details.push(lang === 'ar' ? `الدين الحالي: ${bal} د.م.` : `Dette actuelle : ${bal} DH`)
      }
      if (params.permission) {
        details.push(`Permission: ${params.permission}`)
      }
      if (params.reason) {
        details.push(String(params.reason))
      }
      if (params.detail && !details.length) {
        details.push(String(params.detail))
      }
      return details.length ? `${base} (${details.join(' · ')})` : base
    }
    return `${code}${params.detail ? ` : ${params.detail}` : ''}`
  }
  if (err instanceof Error) {
    if (dict[err.message]) return dict[err.message]
    return err.message
  }
  return String(err)
}

